function getByPath(target, path) {
  return path.split('.').reduce((value, part) => value?.[part], target);
}

function formatMessage(template, variables) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => {
    return variables[key] == null ? '' : String(variables[key]);
  });
}

export function resolveLocale(locale) {
  return supportedLocales.some((item) => item.id === locale) ? locale : DEFAULT_LOCALE;
}

export function getLocaleMeta(locale) {
  return supportedLocales.find((item) => item.id === resolveLocale(locale)) ?? supportedLocales[1];
}

export function t(locale, key, variables = {}) {
  const normalizedLocale = resolveLocale(locale);
  const template = getByPath(messages[normalizedLocale], key) ?? getByPath(messages[DEFAULT_LOCALE], key) ?? key;
  return formatMessage(template, variables);
}

export function getLocalizedText(locale, value) {
  if (value == null) {
    return '';
  }

  if (typeof value === 'string') {
    return value;
  }

  const normalizedLocale = resolveLocale(locale);
  return value[normalizedLocale] ?? value[DEFAULT_LOCALE] ?? value.az ?? '';
}

export function readLocaleFromCookie(cookieHeader = '') {
  const localeToken = cookieHeader
    .split(';')
    .map((part) => part.trim())
    .find((part) => part.startsWith(`${LANGUAGE_COOKIE_KEY}=`));

  if (!localeToken) {
    return DEFAULT_LOCALE;
  }

  const rawLocale = localeToken.slice(LANGUAGE_COOKIE_KEY.length + 1);
  return resolveLocale(decodeURIComponent(rawLocale));
}